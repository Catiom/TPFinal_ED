list    p=16f887
#include <p16f887.inc>

__CONFIG _CONFIG1, _INTRC_OSC_NOCLKOUT & _WDT_OFF & _PWRTE_ON & _MCLRE_OFF & _CP_OFF & _CPD_OFF & _BOR_OFF & _IESO_OFF & _FCMEN_OFF & _LVP_OFF & _DEBUG_OFF
__CONFIG _CONFIG2, _BOR40V & _WRT_OFF

CBLOCK 0x20
    PUNTEROINGRESO;20: APUNTA A LOS INGRESOS POR TECLADO
    PUNTERODIGITO;21: APUNTA A LOS DIGITOS DE CADA BLOQUE
    PUNTEROESTADO;22
    CONTADORDIG1;23: SI ES 3 SALTA AL SIGUIENTE BLOQUE
    CONTADORCODIGO;24: SI ES 4 TERMINA DE COMPARAR
    INGRESO1;25: 3 DIGITOS INGRESADOS POR TECLADO
    INGRESO2;26
    INGRESO3;27
    TEMP;28: RETORNO DE PUNTERODIGITO
    PRUEBA;29
    COINCIDENCIAS;2A: RETORNO DE COMPARARCODIGO
    COSTOCOINCIDENCIA;2B
    DESBORDETIMER
ENDC
    
CBLOCK 0x30;3 BLOQUES DE MEMORIA QUE GUARDAN CADA UNO: CODIGO DE 3 DIGITOS (3 BYTES), PRECIO, ESTADO (OCUAPDO O NO)
    DIGITO11
    DIGITO12
    DIGITO13
    COSTO1
    ESTADO1
ENDC
    
CBLOCK 0x35
    DIGITO21
    DIGITO22
    DIGITO23
    COSTO2
    ESTADO2
ENDC
    
CBLOCK 0x3A
    DIGITO31
    DIGITO32
    DIGITO33
    COSTO3
    ESTADO3
ENDC
    
ORG 0x00
GOTO INICIO
ORG 0x04
GOTO INCREMENTARCOSTO ;INTERRUPCION TIMER0
    
INICIO
    MOVLW 0x30
    MOVWF PUNTERODIGITO
    MOVLW 0x26
    MOVWF PUNTEROINGRESO
    MOVLW 0x34
    MOVWF PUNTEROESTADO
    
    MOVLW B'01000110' ;3 BLOQUES DE PRUEBA
    MOVWF DIGITO11
    MOVLW B'11100010'
    MOVWF DIGITO12
    MOVLW B'11000111'
    MOVWF DIGITO13
    MOVLW D'50'
    MOVWF COSTO1
    INCF ESTADO1
    
    MOVLW B'11111111'
    MOVWF DIGITO21
    MOVLW B'00001111'
    MOVWF DIGITO22
    MOVLW B'11001011'
    MOVWF DIGITO23
    MOVLW D'32'
    MOVWF COSTO2
    INCF ESTADO2
    
    MOVLW B'10011011'
    MOVWF DIGITO31
    MOVLW B'00011011'
    MOVWF DIGITO32
    MOVLW B'11001010'
    MOVWF DIGITO33
    MOVLW D'67'
    MOVWF COSTO3
    INCF ESTADO3
    
    MOVLW B'10011011' ;BLOQUE DE PRUEBA: INGRESO IGUAL A BLOQUE 3
    MOVWF INGRESO1
    MOVLW B'00011011'
    MOVWF INGRESO2
    MOVLW B'11001010'
    MOVWF INGRESO3
    
    MOVLW D'2'
    MOVWF PRUEBA
    ASD
    DECFSZ PRUEBA,1
    GOTO BUCLE
    GOTO FIN
    
    BUCLE
    CALL INCREMENTARCOSTO
    GOTO ASD

RECORRERDIGITOS;FSR EN 0X30, SE MUEVE 3 POSICIONES LUEGO SALTA 2 POSICIONES, ANTES DEL PRIMER DIGITO DEL SIGUIENTE VEHICULO
    MOVLW 0x3F
    SUBWF PUNTERODIGITO,0 ;AL LLEGAR A 0x3F, VUELVO A 0x30
    MOVLW 0x30
    BTFSC STATUS,Z
    MOVWF PUNTERODIGITO
    
    MOVF PUNTERODIGITO,0 
    MOVWF FSR
    MOVF INDF,0
    MOVWF TEMP
    INCF CONTADORDIG1,1
    MOVLW D'3'
    SUBWF CONTADORDIG1,0
    BTFSC STATUS,Z
    GOTO SALTO
    GOTO RETORNO1
    
    SALTO
    MOVLW D'2'
    ADDWF PUNTERODIGITO,1
    CLRF CONTADORDIG1
    BCF STATUS,Z
    GOTO RETORNO1
    
    RETORNO1
    INCF PUNTERODIGITO,1
    RETURN
    
COMPARARCODIGO;LLAMA A RECORRERDIGITOS Y COMPARA CON INGRESOS. INCREMENTA COINCIDENCIAS O SALTA DE BLOQUE
    INCF CONTADORCODIGO,1
    MOVLW D'4'
    SUBWF CONTADORCODIGO,0
    BTFSC STATUS,Z
    GOTO RETORNO2
    CALL RECORRERDIGITOS
    MOVF PUNTEROINGRESO,0
    MOVWF FSR
    MOVF INDF,0
    SUBWF TEMP,0
    BTFSC STATUS,Z
    GOTO COINCIDE
    GOTO NOCOINCIDE;NO COINCIDE, SOLO SALTO AL SIGUIENTE BLOQUE
    
    COINCIDE;INCREMENTA COINCIDENCIAS Y SE MUEVE AL SIGUIENTE BYTE
    BCF STATUS,Z
    INCF COINCIDENCIAS,1
    INCF PUNTEROINGRESO,1
    GOTO COMPARARCODIGO
    
    NOCOINCIDE
    INCF PUNTEROINGRESO,1
    GOTO COMPARARCODIGO
    
    RETORNO2
    MOVLW 0x26
    MOVWF PUNTEROINGRESO
    CLRF CONTADORCODIGO
    CALL VERIFCOINCIDENCIA
    RETURN
    
VERIFCOINCIDENCIA;RETORNA COSTOCOINCIDENCIA
    MOVLW D'3'
    SUBWF COINCIDENCIAS,0
    BTFSC STATUS,Z
    GOTO MOVERCOSTO
    GOTO RETORNO3
    
    MOVERCOSTO
    BCF STATUS,Z
    DECF PUNTERODIGITO,1
    DECF PUNTERODIGITO,1
    MOVF PUNTERODIGITO,0
    MOVWF FSR
    MOVF INDF,0
    MOVWF COSTOCOINCIDENCIA
    INCF PUNTERODIGITO,1
    INCF PUNTERODIGITO,1
    GOTO RETORNO3
    
    RETORNO3
    CLRF COINCIDENCIAS
    RETURN
    
INCREMENTARCOSTO;RECORRE LOS 3 BLOQUES. INCREMENTA SI EL LUGAR ESTA OCUPADO
    ;CHECKDESBORDE
    ;BCF INTCON,2
    ;INCF DESBORDETIMER,1
    ;MOVLW D'76'
    ;SUBWF DESBORDETIMER,0;76 DESBORDES CON PRESCALER 1:256 APROX 5s
    ;BTFSS STATUS,Z
    ;GOTO RETORNO4
    
    CHECKBLOQUE
    MOVLW 0x43 ;SI ME PASO DEL TERCER BLOQUE, RETORNO DE LA INTERRUPCION
    SUBWF PUNTEROESTADO,0
    BTFSC STATUS,Z
    GOTO RETORNO4
    
    VERIFICARESTADO; SI ES 1 INCREMENTO
    MOVF PUNTEROESTADO,0
    MOVWF FSR
    BTFSC INDF,0
    GOTO INCREMENTO
    GOTO SIGUIENTEESTADO
    
    INCREMENTO
    DECF FSR,1
    INCF INDF,1
    GOTO SIGUIENTEESTADO
    
    SIGUIENTEESTADO
    MOVLW D'5'
    ADDWF PUNTEROESTADO,1
    GOTO CHECKBLOQUE
    
    RETORNO4; RECCARGO PUNTERO AL PRIMER ESTADO Y RETORNO
    MOVLW 0x34
    MOVWF PUNTEROESTADO
    BCF STATUS,Z
    CLRF TMR0
    RETFIE
 
FIN
END
